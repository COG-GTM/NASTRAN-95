"""Generate ``python/PARITY.md`` from a pytest run.

``record_parity`` rows (``tests/conftest.py``) carry tags: ``deck``/``table`` for
the RF1 listing comparisons of ``tests/test_solve_static.py`` and
``element``/``quantity``/``source`` for Python vs the Fortran element harness.
``pytest --parity-json PATH`` writes them with the test outcomes; this module turns
that file into PARITY.md.

    python -m tests.parity_report                      # run pytest, write PARITY.md
    python -m tests.parity_report --from parity.json   # render an existing run
    python -m tests.parity_report --from parity.json --check   # fail if stale (CI)

``--check`` compares text and integers exactly; errors are equal when both are below
``NOISE_FLOOR`` or within ``ERROR_RTOL`` of each other, since the last bits of the
BLAS/LAPACK results differ between machines.
"""

from __future__ import annotations

import argparse
import difflib
import json
import math
import os
import re
import subprocess
import sys
import tempfile
from collections import defaultdict
from pathlib import Path

from nastran95py.reference.golden import ATOL_SCALE, MARGIN_COLUMNS, MARGIN_RTOL, RTOL
from nastran95py.reference.inventory import RF1_DECKS

PACKAGE_ROOT = Path(__file__).resolve().parent.parent
PARITY_MD = PACKAGE_ROOT / "PARITY.md"
SUITE = "tests/test_solve_static.py"

ELEMENTS = ("CROD/CONROD", "CSHEAR", "CTRMEM", "CQDMEM", "CQDMEM1", "CQDMEM2")
QUANTITIES = (("K", "K"), ("M", "M"), ("load", "thermal load"), ("stress", "stress"))
KIND_LABELS = {
    "displacement": "displacement",
    "spcforce": "SPC force",
    "oload": "OLOAD",
    "force": "force",
    "stress": "stress",
}
NOISE_FLOOR = 1e-12
ERROR_RTOL = 0.05
_ERR = re.compile(r"\d\.\d{2}e[+-]\d{2}")


class ParityError(RuntimeError):
    pass


def _e(x: float) -> str:
    return f"{x:.2e}"


def _max(rows: list[dict]) -> tuple[int, float, float]:
    return (
        sum(r["n"] for r in rows),
        max(r["max_abs"] for r in rows),
        max(r["max_rel"] for r in rows),
    )


def _validate(data: dict) -> None:
    if data["exitstatus"] != 0:
        failed = [o["nodeid"] for o in data["outcomes"] if o["outcome"] == "failed"]
        raise ParityError(f"pytest exit status {data['exitstatus']}; failed: {failed}")
    records = data["records"]
    decks = {r["deck"] for r in records if "deck" in r}
    if missing := sorted(set(RF1_DECKS) - decks):
        raise ParityError(f"no listing parity rows for decks {missing} (partial run?)")
    have = {(r["element"], r["quantity"]) for r in records if r.get("source") == "golden"}
    missing = [(e, q) for e in ELEMENTS for q, _ in QUANTITIES if (e, q) not in have]
    if missing:
        raise ParityError(f"no harness parity rows for {missing} (gfortran missing?)")


def _deck_rows(records: list[dict], deck: str) -> list[tuple[str, int, int, float, float]]:
    groups: dict[tuple[str, str], list[dict]] = defaultdict(list)
    for r in records:
        if r.get("deck") != deck or "/" not in r["table"]:
            continue
        kind, what, sc, _occ = r["table"].split("/")[:4]
        groups[(kind, what)].append({**r, "subcase": sc})
    order = list(KIND_LABELS)
    out = []
    for (kind, what), rows in sorted(
        groups.items(), key=lambda kv: (order.index(kv[0][0]), kv[0][1])
    ):
        label = KIND_LABELS[kind] if what == "grid" else f"{what} {KIND_LABELS[kind]}"
        n, a, rel = _max(rows)
        subcases = ", ".join(sorted({r["subcase"][2:] for r in rows}, key=int))
        out.append((label, subcases, n, a, rel))
    return out


def _outcomes(data: dict) -> tuple[dict[str, int], list[dict]]:
    counts: dict[str, int] = defaultdict(int)
    xfails = []
    for o in data["outcomes"]:
        if not o["nodeid"].startswith(SUITE):
            continue
        counts[o["outcome"]] += 1
        if o["outcome"] == "xfailed":
            xfails.append(o)
    return dict(counts), xfails


def render(data: dict) -> str:
    """PARITY.md for the run in ``data`` (the ``--parity-json`` file)."""
    from tests import test_solve_static as S

    _validate(data)
    records = data["records"]
    counts, xfails = _outcomes(data)
    summary = ", ".join(
        f"{counts[k]} {k}" for k in ("passed", "xfailed", "skipped") if counts.get(k)
    )
    margins = ", ".join(f"`{c}`" for c in MARGIN_COLUMNS)
    lines = [
        "# RF1 static solve parity",
        "",
        "<!-- Generated by `python -m tests.parity_report` from the pytest run; do not edit. -->",
        "",
        "`nastran95py.solve.static` against the COSMIC listings in `../demoout/` (the Fortran",
        "golden files parsed into `tests/reference/golden/`), and each ported element kernel",
        "against the Fortran element harness (`tests/fortran_harness/`). Regenerate with",
        "`python -m tests.parity_report`; CI fails when this file is stale.",
        "",
        f"Parity suite (`{SUITE}`): {summary}.",
        "",
        "## Listing parity per deck",
        "",
        f"Tolerance: `|actual - golden| <= atol + rtol * |golden|` with rtol {RTOL:g} and atol",
        f"{ATOL_SCALE:g} * max|golden| of the column ({MARGIN_RTOL:g} rtol for safety margins).",
        "Max rel error counts only values above that column's atol, where a relative error",
        "is meaningful. Values are the printed (non-blank) listing entries compared.",
        "",
        "| Deck | Quantity | Subcases | Values | Max abs error | Max rel error |",
        "|---|---|---|---:|---:|---:|",
    ]
    for deck in RF1_DECKS:
        if deck in S.KGGX_ONLY:
            (r,) = [x for x in records if x.get("deck") == deck and x["table"] == "kggx"]
            lines.append(
                f"| {deck} | K_gg vs printed KGGX | - | {r['n']} | {_e(r['max_abs'])} "
                f"| {_e(r['max_rel'])} |"
            )
            continue
        for label, subcases, n, a, rel in _deck_rows(records, deck):
            lines.append(f"| {deck} | {label} | {subcases} | {n} | {_e(a)} | {_e(rel)} |")
    lines += [
        "",
        "## Element harness parity",
        "",
        "Max relative error (max |error| / max |Fortran| per case, worst case) of the Python",
        "kernels, reference and batched paths, against the Fortran element harness dumps",
        "checked in under `tests/fortran_harness/golden/`. Stress covers the phase-1 SDR2",
        "matrices and the phase-2 stress, force and principal-angle words. Each CI job also",
        "rebuilds the harness with its own gfortran and repeats these comparisons live.",
        "",
        "| Element | " + " | ".join(q for _, q in QUANTITIES) + " |",
        "|---|" + "---:|" * len(QUANTITIES),
    ]
    for elem in ELEMENTS:
        mine = [r for r in records if r.get("element") == elem and r.get("source") == "golden"]
        cells = []
        for q, _ in QUANTITIES:
            cells.append(_e(_max([r for r in mine if r["quantity"] == q])[2]))
        lines.append(f"| {elem} | " + " | ".join(cells) + " |")
    (quantum,) = [r for r in records if r.get("table") == "quantum-rows"]
    occ = sorted({k.split("/")[3] for k in S.tables(S.load_golden("d01161a"))} - {"occ1"})
    lines += [
        "",
        "## Relaxations",
        "",
        "Every place the suite compares less than every listing value at the baseline",
        "tolerance:",
        "",
        f"- **d01013a CROD post axial forces** (`{S.D01013A_POST_FORCES}`, EIDs",
        f"  {', '.join(map(str, S.D01013A_QUANTUM_ROWS))}): left out of the table above and",
        "  run as strict xfails at the baseline tolerance. SROD2 cancels two REAL dot",
        "  products of about 1e6, so the force moves in REAL steps; each listed value is",
        "  reproduced by moving one end's T3 by one float32 ulp",
        "  (`test_d01013a_post_axial_forces_are_one_real_quantum_off`). Unperturbed:",
        f"  {quantum['n']} values, max abs {_e(quantum['max_abs'])}, "
        f"max rel {_e(quantum['max_rel'])}.",
    ]
    for o in xfails:
        lines.append(f"  - `{o['nodeid'].removeprefix(SUITE + '::')}` xfailed (strict)")
    lines += [
        "- **t01241a has no solution tables**: its DMAP ALTER prints KGGX and stops before",
        "  SSG3. The assembled `K_gg` is compared with KGGX, and the solve must raise",
        "  `SingularStiffness` for FORCE 1 on the unstiffened DOF (4, 3).",
        "- **d01161a fully stressed design**: only occurrence 1 (the as-input analysis) is",
        f"  compared; the resized-design occurrences ({', '.join(occ)}) are parsed but not",
        "  solved, since POPT/PLIMIT resizing is out of scope.",
        f"- **Safety margins** ({margins}) use rtol {MARGIN_RTOL:g} instead of",
        f"  {RTOL:g}: the listings print them to 2 significant figures. They are included",
        "  in the stress rows above (d01161a CROD stress is its margin column).",
        "",
    ]
    return "\n".join(lines)


def _split(text: str) -> tuple[str, list[float]]:
    return _ERR.sub("#", text), [float(x) for x in _ERR.findall(text)]


def stale(current: str, committed: str) -> list[str]:
    """Differences between two renderings beyond machine noise (empty if current)."""
    (cur, cur_v), (old, old_v) = _split(current), _split(committed)
    if cur != old or len(cur_v) != len(old_v):
        return list(difflib.unified_diff(
            committed.splitlines(), current.splitlines(), "committed", "current", lineterm=""
        ))  # fmt: skip
    out = []
    for i, (a, b) in enumerate(zip(cur_v, old_v, strict=True)):
        if max(a, b) <= NOISE_FLOOR or math.isclose(a, b, rel_tol=ERROR_RTOL):
            continue
        out.append(f"error #{i + 1}: committed {b:.2e}, current {a:.2e}")
    return out


def run_suite(json_path: Path, pytest_args: list[str]) -> int:
    env = {**os.environ, "NASTRAN95PY_REQUIRE_FORTRAN": "1"}
    cmd = [sys.executable, "-m", "pytest", "-q", f"--parity-json={json_path}", *pytest_args]
    return subprocess.run(cmd, cwd=PACKAGE_ROOT, env=env).returncode


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--from", dest="source", type=Path, help="existing --parity-json file")
    parser.add_argument("--check", action="store_true", help="fail if PARITY.md is stale")
    parser.add_argument("--output", type=Path, default=PARITY_MD)
    args = parser.parse_args(argv)
    if args.source is None:
        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp) / "parity.json"
            run_suite(path, [])
            data = json.loads(path.read_text())
    else:
        data = json.loads(args.source.read_text())
    try:
        text = render(data)
    except ParityError as exc:
        print(f"parity_report: {exc}", file=sys.stderr)
        return 1
    if args.check:
        committed = args.output.read_text() if args.output.exists() else ""
        if diff := stale(text, committed):
            print(f"{args.output.name} is stale; run `python -m tests.parity_report`:")
            print("\n".join(diff))
            return 1
        print(f"{args.output.name} is current")
        return 0
    args.output.write_text(text)
    print(f"wrote {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
