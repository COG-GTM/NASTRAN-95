C     STUBS FOR THE ROD AND SHEAR LOAD HARNESSES (RODLOAD.F, TSHEARLD.F):
C     THE EDTL DATA SOURCES (SSGETD ELEMENT AND GRID TEMPERATURES, FEDT
C     ELEMENT DEFORMATION) AND THE
C     CSTM FILE BASGLB READS (ITS READ IS RENAMED CSTMRD IN THE MAKEFILE).
C
      SUBROUTINE SSGETD (ELID,TI,GRIDS)
      INTEGER ELID,GRIDS
      REAL    TI(*)
      COMMON /HLOAD / TSTUB,DSTUB,NCSTM,ICS,ICSTM0
      COMMON /HTGRID/ TGRID(32)
      TI(1) = TSTUB
      DO 10 I = 1,GRIDS
   10 TI(I+1) = TGRID(I)
      RETURN
      END
C
      SUBROUTINE FEDT (IED1,DELTA,IDEF)
      COMMON /HLOAD / TSTUB,DSTUB,NCSTM,ICS,ICSTM0
      DELTA = DSTUB
      RETURN
      END
C
      SUBROUTINE CSTMRD (*,*,FILE,BUF,N,NOEOR,FLAG)
      INTEGER FILE,N,NOEOR,FLAG,BUF(N)
      COMMON /ZZZZZZ/ IZ(300000)
      COMMON /HLOAD / TSTUB,DSTUB,NCSTM,ICS,ICSTM0
      IF (ICS .GE. NCSTM) RETURN 1
      K = ICSTM0 + 14*ICS
      DO 10 I = 1,N
   10 BUF(I) = IZ(K+I-1)
      ICS = ICS + 1
      RETURN
      END
C
      SUBROUTINE BCKREC (FILE)
      INTEGER FILE
      COMMON /HLOAD / TSTUB,DSTUB,NCSTM,ICS,ICSTM0
      ICS = 0
      RETURN
      END
