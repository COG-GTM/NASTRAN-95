C     EXECUTIVE STUBS FOR THE ELEMENT HARNESS (IN ADDITION TO THE GINO
C     AND MAT STUBS IN ../FORTRAN_KERNELS/STUBS.F).
C
C     EMGOUT AND SMA1B ARE WHERE THE ELEMENT ROUTINES HAND OVER THEIR
C     MATRICES; HERE THEY PRINT THEM INSTEAD OF WRITING GINO FILES.
C
      SUBROUTINE EMGOUT (RBUF,DBUF,LBUF,EOE,DICT,FILE,INPREC)
      INTEGER          LBUF,EOE,DICT(5),FILE,INPREC
      REAL             RBUF(LBUF)
      DOUBLE PRECISION DBUF(LBUF)
      WRITE (*,'(A,6I8)') 'MATRIX',FILE,DICT(2),DICT(3),DICT(4),LBUF,
     1                    INPREC
      IF (INPREC .EQ. 2) THEN
         WRITE (*,'(4(1X,ES25.16E3))') (DBUF(I),I=1,LBUF)
      ELSE
         WRITE (*,'(6(1X,ES16.8E3))') (RBUF(I),I=1,LBUF)
      END IF
      RETURN
      END
C
      SUBROUTINE SMA1B (KE,J,II,IFILE,DAMPC)
      DOUBLE PRECISION KE(36),DAMPC
      INTEGER          J,II,IFILE
      COMMON /SMA1IO/  ISMA(10),IFKGG,IGKGG,IF4GG,ISMB(23)
      COMMON /SMA1CL/  IOPT4,K4GGSW,NPVT
      IF (IFILE .NE. IFKGG) RETURN
      WRITE (*,'(A,3I8)') 'PART',NPVT,J,II
      WRITE (*,'(4(1X,ES25.16E3))') KE
      RETURN
      END
