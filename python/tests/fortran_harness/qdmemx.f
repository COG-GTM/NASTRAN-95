C     CQDMEM HARNESS DRIVER FOR THE ROUTINES OUTSIDE THE ELEMENT DRIVER:
C     THE THERMAL LOAD QDMEM (MIS/QDMEM.F, AS CALLED FROM EDTL; FOUR
C     TRIMEM (1) CALLS) AND THE LUMPED MASS MASSTQ (1) (MIS/MASSTQ.F,
C     THE MASS PATH OF EMGOLD FOR QDMEMS/QDMEMD).
C
C     STDIN:  NM1 / MAT1 LINES, NM2 / MAT2 LINES, NCS / CSTM LINES (SAME
C             FORMAT AS DRIVER.F), THEN NCASE AND FOR EACH CASE
C               KIND NAME N
C               IFLAG(1..N)     1 = INTEGER WORD, 0 = REAL WORD
C               VALUE(1..N)     CQDMEM ECPT RECORD
C             KIND 4 (QDMEM):  TBAR NPG
C             KIND 5 (MASSTQ): NPIV SIL(1..NPIV)
C             BASGLB READS THE CSTM THROUGH THE CSTMRD STUB (LOADSTUBS.F),
C             SO THE GRIDS OF ONE ELEMENT MAY USE DIFFERENT SYSTEMS.
C
C     STDOUT: PER CASE 'CASE n KIND NAME', THEN
C             QDMEM:  'LOAD npg' + PG(1..NPG) REAL WORDS (INDEXED BY SIL)
C             MASSTQ: 'PART npvt jsil ii' + 36 DOUBLE WORDS PER PIVOT
C             AND 'END'.
C
      PROGRAM QDMEMX
      INTEGER          IZ(300000),BFR(10),N2MAT,KIND,N,IFLAG(400)
      REAL             R(16),WORDS(400),PG(400),TARR(5)
      INTEGER          IWORDS(400),ISIL(10)
      DOUBLE PRECISION XVAL(400)
      CHARACTER*8      NAME
      LOGICAL          HEAT2
      COMMON /ZZZZZZ/  Z(300000)
      COMMON /SYSTEM/  ISYS(100)
      COMMON /NAMES /  RD,RDREW,WRT,WRTREW,CLSREW
      INTEGER          RD,RDREW,WRT,WRTREW,CLSREW
      COMMON /HSTUB /  NM1,M1(12,200),NM2,M2(17,200),ICARD,IPOS
      COMMON /CONDAS/  CONSTS(5)
      COMMON /TRIMEX/  ITRX(100)
      COMMON /SMA2ET/  ISMA2(100)
      COMMON /SMA2CL/  IOPTB,BGGIND,NPVT2,ISM2CL(20)
      COMMON /SMA2HT/  HEAT2
      COMMON /SMA2IO/  ISM2IO(36)
      COMMON /LOADX /  LC(4),CSTM,LC1(10),IDUM(3),ICM
      INTEGER          CSTM
      COMMON /HLOAD /  TSTUB,DSTUB,NCSTM,ICS,ICSTM0
      EQUIVALENCE      (Z(1),IZ(1)),(WORDS(1),IWORDS(1))
      PARAMETER        (ICSTM = 200001)
      ISYS(1) = 1000
      ISYS(2) = 6
      ISYS(9) = 50
      ISYS(10)= 0
      ISYS(40)= 32
      RD = 2
      RDREW = 0
      WRT = 3
      WRTREW = 1
      CLSREW = 1
      CONSTS(1) = 4.0*ATAN(1.0)
      CONSTS(2) = 2.0*CONSTS(1)
      CONSTS(3) = 180.0/CONSTS(1)
      CONSTS(4) = CONSTS(1)/180.0
      CONSTS(5) = 4.0*CONSTS(1)**2
      READ (*,*) NM1
      DO 10 I = 1,NM1
      READ (*,*) M1(1,I),(R(J),J=1,10)
      DO 5 J = 1,10
    5 M1(J+1,I) = TRANSFER(R(J),0)
   10 M1(12,I) = 0
      READ (*,*) NM2
      DO 20 I = 1,NM2
      READ (*,*) M2(1,I),(R(J),J=1,15)
      DO 15 J = 1,15
   15 M2(J+1,I) = TRANSFER(R(J),0)
   20 M2(17,I) = 0
      READ (*,*) NCSTM
      DO 30 I = 1,NCSTM
      K = ICSTM + 14*(I-1)
      READ (*,*) IZ(K),IZ(K+1),(Z(K+J),J=2,13)
   30 CONTINUE
      ICSTM0 = ICSTM
      ICS = 0
      CALL PREMAT (IZ(1),Z(1),BFR,100000,N2MAT,101,0)
      CSTM = 204
      ICM  = 0
      HEAT2 = .FALSE.
      IOPTB = 0
      ISM2IO(11) = 203
C
      READ (*,*) NCASE
      DO 900 IC = 1,NCASE
      READ (*,*) KIND,NAME,N
      READ (*,*) (IFLAG(J),J=1,N)
      READ (*,*) (XVAL(J),J=1,N)
      DO 40 J = 1,N
      IF (IFLAG(J) .EQ. 1) THEN
         IWORDS(J) = NINT(XVAL(J))
      ELSE
         WORDS(J) = REAL(XVAL(J))
      END IF
   40 CONTINUE
      WRITE (*,'(A,2I6,1X,A)') 'CASE',IC,KIND,NAME
      IF (KIND .EQ. 5) GO TO 500
C
C     QDMEM: THERMAL LOAD INTO PG AT THE GRID SILS (T(1) = TBAR)
C
      READ (*,*) TBAR,NPG
      DO 410 J = 1,100
  410 ITRX(J) = 0
      DO 420 J = 1,N
  420 ITRX(J) = IWORDS(J)
      DO 430 J = 1,NPG
  430 PG(J) = 0.0
      TARR(1) = TBAR
      CALL QDMEM (TARR,PG)
      WRITE (*,'(A,I8)') 'LOAD',NPG
      WRITE (*,'(6(1X,ES16.8E3))') (PG(J),J=1,NPG)
      GO TO 800
C
C     MASSTQ (1): ONE CALL PER PIVOT SIL, SMA2B PRINTS THE PARTITION
C
  500 READ (*,*) NPIV,(ISIL(J),J=1,NPIV)
      DO 550 IP = 1,NPIV
      DO 510 J = 1,100
  510 ISMA2(J) = 0
      DO 520 J = 1,N
  520 ISMA2(J) = IWORDS(J)
      NPVT2 = ISIL(IP)
      CALL MASSTQ (1)
  550 CONTINUE
C
  800 WRITE (*,'(A)') 'END'
  900 CONTINUE
      END
C
      SUBROUTINE SMA2B (ME,J,II,IFILE,DAMPC)
      DOUBLE PRECISION ME(36),DAMPC
      INTEGER          J,II,IFILE
      COMMON /SMA2CL/  IOPTB,BGGIND,NPVT
      WRITE (*,'(A,3I8)') 'PART',NPVT,J,II
      WRITE (*,'(4(1X,ES25.16E3))') ME
      RETURN
      END
C
      SUBROUTINE HMAT (ID)
      WRITE (*,'(A)') 'HMAT CALLED (HEAT TRANSFER NOT SUPPORTED)'
      STOP 4
      END
