C     GINO/EXECUTIVE STUBS FOR THE SHARED-KERNEL PARITY HARNESS.
C     THE MPT IS SIMULATED BY /HSTUB/: MAT1 (CARD 103) AND MAT2 (CARD
C     203) RECORDS LOADED BY THE DRIVER.
C
      BLOCK DATA HSTUBD
      COMMON /HSTUB/ NM1,M1(12,200),NM2,M2(17,200),ICARD,IPOS
      DATA NM1,NM2,ICARD,IPOS /0,0,0,0/
      END
C
      SUBROUTINE PRELOC (*,BFR,FILE)
      INTEGER BFR(1),FILE
      RETURN
      END
C
      SUBROUTINE LOCATE (*,BFR,ID,FLAG)
      INTEGER BFR(1),ID(2),FLAG
      COMMON /HSTUB/ NM1,M1(12,200),NM2,M2(17,200),ICARD,IPOS
      ICARD = 0
      IPOS  = 0
      IF (ID(1).EQ.103 .AND. NM1.GT.0) ICARD = 1
      IF (ID(1).EQ.203 .AND. NM2.GT.0) ICARD = 2
      IF (ICARD .EQ. 0) RETURN 1
      RETURN
      END
C
      SUBROUTINE READ (*,*,FILE,BUF,N,NOEOR,FLAG)
      INTEGER FILE,BUF(N),N,NOEOR,FLAG
      COMMON /HSTUB/ NM1,M1(12,200),NM2,M2(17,200),ICARD,IPOS
      IPOS = IPOS + 1
      IF (ICARD .EQ. 1) THEN
         IF (IPOS .GT. NM1) RETURN 2
         DO 10 I = 1,N
   10    BUF(I) = M1(I,IPOS)
      ELSE IF (ICARD .EQ. 2) THEN
         IF (IPOS .GT. NM2) RETURN 2
         DO 20 I = 1,N
   20    BUF(I) = M2(I,IPOS)
      ELSE
         RETURN 1
      END IF
      RETURN
      END
C
      SUBROUTINE CLOSE (FILE,OPT)
      INTEGER FILE,OPT
      RETURN
      END
C
      SUBROUTINE SSWTCH (N,J)
      J = 0
      RETURN
      END
C
      SUBROUTINE MESAGE (N,P1,P2)
      INTEGER N,P1,P2(2)
      WRITE (*,'(A,3I12)') 'MESAGE ',N,P1,P2(1)
      IF (N .LT. 0) STOP 2
      RETURN
      END
C
      SUBROUTINE ERRTRC (NAME,N)
      CHARACTER*8 NAME
      WRITE (*,'(A,A8,I8)') 'ERRTRC ',NAME,N
      STOP 3
      END
C
C     WORD ADDRESS RELATIVE TO OPEN CORE, SO THAT PREMAT/PRETRS OFFSETS
C     STAY SMALL ON 64-BIT HOSTS.
C
      INTEGER FUNCTION LOCFX (X)
      COMMON /ZZZZZZ/ Z(300000)
      LOCFX = INT((LOC(X) - LOC(Z(1)))/4)
      RETURN
      END
