C     GINO STUBS FOR THE BASGLB PARITY HARNESS. THE CSTM DATA BLOCK IS
C     ONE LOGICAL RECORD OF 14-WORD ENTRIES HELD IN /CSTUB/; READ RETURNS
C     THE NEXT ENTRY (RETURN 2 AT END OF RECORD), BCKREC REWINDS TO ITS
C     START, AS GINO DOES FOR A SINGLE-RECORD FILE.
C
      BLOCK DATA CSTUBD
      COMMON /CSTUB/ NREC,IW(14,200),IPOS
      DATA NREC,IPOS /0,0/
      END
C
      SUBROUTINE READ (*,*,FILE,BUF,N,NOEOR,FLAG)
      INTEGER FILE,BUF(N),N,NOEOR,FLAG
      COMMON /CSTUB/ NREC,IW(14,200),IPOS
      IF (IPOS .GE. NREC) RETURN 2
      IPOS = IPOS + 1
      DO 10 I = 1,N
   10 BUF(I) = IW(I,IPOS)
      RETURN
      END
C
      SUBROUTINE BCKREC (FILE)
      INTEGER FILE
      COMMON /CSTUB/ NREC,IW(14,200),IPOS
      IPOS = 0
      RETURN
      END
C
      SUBROUTINE MESAGE (N,P1,P2)
      INTEGER N,P1,P2(2)
      WRITE (*,'(A,3I12)') 'MESAGE ',N,P1,P2(1)
      IF (N .LT. 0) STOP 2
      RETURN
      END
