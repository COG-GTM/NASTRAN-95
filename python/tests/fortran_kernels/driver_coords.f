C     BASGLB PARITY DRIVER. READS LIST-DIRECTED INPUT ON STDIN:
C       NCSTM, THEN NCSTM LINES: CID TYPE X0 Y0 Z0 T11 ... T33
C       NCASE, THEN NCASE LINES: KIND CID X Y Z V1 V2 V3
C         KIND 1 (BASGLB) : BASIC VECTOR V AT POINT -> GLOBAL VOUT(3)
C         KIND 2 (GLBBAS) : GLOBAL VECTOR V AT POINT -> BASIC VOUT(3)
C         KIND 3 (GBTRAN) : GLOBAL-TO-BASIC T(9) AT POINT, BY ROWS
C     GBTRAN IS ONLY CALLED FOR BASIC AND RECTANGULAR SYSTEMS: FOR
C     CYLINDRICAL/SPHERICAL ONES IT FALLS THROUGH CODE THAT READS VIN1,
C     A DUMMY OF BASGLB ABSENT FROM THE GBTRAN ENTRY, WHICH GFORTRAN
C     PASSES AS A NULL ADDRESS. THOSE MATRICES ARE CHECKED THROUGH GLBBAS
C     ON UNIT VECTORS INSTEAD.
C     ONE OUTPUT LINE PER CASE.
C
      PROGRAM COORDS
      REAL             R(12),PONT(3),V(3),VOUT(3),T(9)
      CHARACTER*512    LINE
      COMMON /SYSTEM/  ISYS(100)
      COMMON /LOADX /  LC(4),ICSTM,LC1(10),IDUM(3),ICM
      COMMON /CSTUB /  NREC,IW(14,200),IPOS
C
      ISYS(1) = 1000
      ISYS(2) = 6
      ICSTM   = 204
      ICM     = 0
      READ (*,*) NREC
      DO 10 I = 1,NREC
      READ (*,*) IW(1,I),IW(2,I),(R(J),J=1,12)
      DO 10 J = 1,12
   10 IW(J+2,I) = TRANSFER(R(J),0)
C
C     BASGLB MUST BE ENTERED ONCE BEFORE GBTRAN (SEE ITS CHECK WORD).
C
      PONT(1) = 0.0
      PONT(2) = 0.0
      PONT(3) = 0.0
      CALL BASGLB (PONT,VOUT,PONT,0)
C
      READ (*,*) NCASE
      DO 100 IC = 1,NCASE
      READ (*,'(A)') LINE
      READ (LINE,*) KIND,ID,PONT,V
      IF (KIND .EQ. 1) THEN
         CALL BASGLB (V,VOUT,PONT,ID)
         WRITE (*,'(3(1X,ES16.8E3))') VOUT
      ELSE IF (KIND .EQ. 2) THEN
         CALL GLBBAS (V,VOUT,PONT,ID)
         WRITE (*,'(3(1X,ES16.8E3))') VOUT
      ELSE
         CALL GBTRAN (ID,PONT,T)
         WRITE (*,'(9(1X,ES16.8E3))') T
      END IF
  100 CONTINUE
      END
