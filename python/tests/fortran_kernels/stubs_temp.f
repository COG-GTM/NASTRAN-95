C     GINO/EXECUTIVE STUBS FOR THE MATT1/TABLEM PARITY HARNESS.
C     EACH LOCATABLE CARD TYPE IS A FLAT WORD STREAM IN /TSTUB/:
C     MAT1 (103), MAT2 (203), MATT1 (703) ON THE MPT AND TABLEM1-4
C     (105, 205, 305, 405) ON THE DIT. READ COPIES N WORDS AND TAKES
C     THE END-OF-RECORD RETURN AT THE END OF THE STREAM.
C
      BLOCK DATA TSTUBD
      COMMON /TSTUB/ ICODE(7),IBEG(7),IEND(7),W(200000),NW,IC,IPOS
      DATA ICODE /103,203,703,105,205,305,405/
      DATA IBEG,IEND /7*1,7*0/
      DATA NW,IC,IPOS /0,0,0/
      END
C
      SUBROUTINE PRELOC (*,BFR,FILE)
      INTEGER BFR(1),FILE
      RETURN
      END
C
      SUBROUTINE LOCATE (*,BFR,ID,FLAG)
      INTEGER BFR(1),ID(2),FLAG,W
      COMMON /TSTUB/ ICODE(7),IBEG(7),IEND(7),W(200000),NW,IC,IPOS
      IC = 0
      DO 10 K = 1,7
      IF (ID(1).EQ.ICODE(K) .AND. IEND(K).GE.IBEG(K)) IC = K
   10 CONTINUE
      IF (IC .EQ. 0) RETURN 1
      IPOS = IBEG(IC)
      RETURN
      END
C
      SUBROUTINE READ (*,*,FILE,BUF,N,NOEOR,FLAG)
      INTEGER FILE,BUF(N),N,NOEOR,FLAG,W
      COMMON /TSTUB/ ICODE(7),IBEG(7),IEND(7),W(200000),NW,IC,IPOS
      IF (IC .EQ. 0) RETURN 1
      IF (IPOS .GT. IEND(IC)) RETURN 2
      DO 10 I = 1,N
   10 BUF(I) = W(IPOS+I-1)
      IPOS = IPOS + N
      RETURN
      END
C
      SUBROUTINE CLOSE (FILE,OPT)
      INTEGER FILE,OPT
      RETURN
      END
C
      SUBROUTINE SSWTCH (N,J)
      J = 0
      RETURN
      END
C
      SUBROUTINE MESAGE (N,P1,P2)
      INTEGER N,P1,P2(2)
      WRITE (*,'(A,3I12)') 'MESAGE ',N,P1,P2(1)
      IF (N .LT. 0) STOP 2
      RETURN
      END
C
      SUBROUTINE ERRTRC (NAME,N)
      CHARACTER*8 NAME
      WRITE (*,'(A,A8,I8)') 'ERRTRC ',NAME,N
      STOP 3
      END
C
      INTEGER FUNCTION LOCFX (X)
      COMMON /ZZZZZZ/ Z(300000)
      LOCFX = INT((LOC(X) - LOC(Z(1)))/4)
      RETURN
      END
